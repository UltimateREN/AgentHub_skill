"use strict";
const assert = require("node:assert/strict");
const { BoundedRegistry, createScopePool } = require("../src/providers/catpaw/scopes.cjs");
const { sessionRecord, CLIENT_TOOL_SESSION_TTL_MS } = require("../src/providers/catpaw/registry.cjs");
const { createEventBridge } = require("../src/execution/event-bridge.cjs");
const { splitDelta } = require("../src/execution/split-delta.cjs");
const { eventBytes } = require("../sdk/provider-protocol.cjs");
const tick = () => new Promise(resolve => setImmediate(resolve));
const record = (id, extra = {}) => sessionRecord({ conversationId: id, accountId: "account", modelType: 83, pendingCallIds: ["call-" + id], ...extra });
async function main() {
  const registry = new BoundedRegistry({ maxRecords: 1 });
  registry.register(record("one"));
  const original = registry.lookupByCallId("call-one");
  const release = registry.claimContinuation(original);
  assert.throws(() => registry.claimContinuation(original), error => error.status === 409);
  original.lastActiveAt = Date.now() - CLIENT_TOOL_SESSION_TTL_MS - 1;
  assert.equal(registry.lookupByCallId("call-one"), null, "expired active record cannot admit a new continuation");
  assert.equal(registry.lookupByConversation("one"), original, "TTL never removes a claimed anonymous record");
  assert.throws(() => registry.register(record("two")), error => error.status === 503);
  assert.equal(registry.lookupByConversation("one"), original);
  release(); release();
  assert.equal(registry.claims.size, 0); assert.equal(registry.anonymous.size, 0);
  registry.register(record("one"));
  const end = registry.claimContinuation(registry.lookupByCallId("call-one"));
  registry.register(record("one", { pendingCallIds: ["next-call"] }));
  end(); assert.ok(registry.lookupByCallId("next-call"), "claim cleanup preserves the replacement");
  assert.equal(registry.lookupByCallId("call-one"), null);
  const cap = new BoundedRegistry({ maxRecords: 2, maxBytes: 900 });
  cap.register(record("a", { fingerprints: ["x".repeat(100)] }));
  cap.register(record("b"));
  const saved = cap.lookupByConversation("a");
  assert.throws(() => cap.register(record("a", { fingerprints: ["x".repeat(1000)] })), /上限/);
  assert.equal(cap.lookupByConversation("a"), saved, "failed replacement preserves old record and unrelated LRU");
  assert.ok(cap.lookupByConversation("b"));
  const idle = new BoundedRegistry();
  idle.register(record("expired", { sessionId: "old-session" }));
  idle.sessions.get("old-session").lastActiveAt = 1;
  assert.equal(idle.markInflight("old-session"), true);
  assert.equal(idle.sessions.has("old-session"), false, "new session claim cannot resurrect an expired mapping");
  idle.releaseInflight("old-session");
  const pool = createScopePool({ maxGroups: 2, globalBytes: 700 });
  const a = pool.acquire("a", "a", "u", "http://x"), b = pool.acquire("b", "b", "u", "http://x");
  a.registry.register(record("a", { fingerprints: ["x".repeat(150)] }));
  assert.throws(() => b.registry.register(record("b", { fingerprints: ["x".repeat(150)] })), /上限/);
  assert.throws(() => pool.acquire("c", "c", "u", "http://x"), /上限/);
  a.release(); b.release(); a.release(); assert.equal(pool.stats().active, 0);
  const next = pool.acquire("c", "c", "u", "http://x"); next.release();
  assert.equal(pool.stats().groups, 2);
  const switched = pool.acquire("c", "c", "new-uid", "http://x"); switched.release();
  assert.equal(pool.stats().active, 0);

  const bridge = createEventBridge(), iterator = bridge.events();
  let ack = false;
  const pending = bridge.send("first").then(() => { ack = true; }, error => error);
  assert.equal((await iterator.next()).value, "first"); await tick(); assert.equal(ack, false);
  await iterator.return(); assert.ok(await pending instanceof Error); assert.equal(ack, false);
  await assert.rejects(bridge.send("late"));
  const success = createEventBridge(), it = success.events();
  const sent = success.send("one"); assert.equal((await it.next()).value, "one");
  const waiting = it.next(); await sent; success.finish(); assert.equal((await waiting).done, true);
  const failed = createEventBridge(); const rejected = assert.rejects(failed.send("queued"), /broken/);
  failed.finish(new Error("broken")); await rejected; await assert.rejects(failed.events().next(), /broken/);
  for (const limit of [400, 600, 1024]) {
    const content = '中文😀\\\"\n'.repeat(1200), args = JSON.stringify({ q: content });
    const delta = { content, reasoning_content: content, tool_calls: [{ index: 0, id: "call", type: "function", function: { name: "lookup", arguments: args } }] };
    const fits = delta => eventBytes({ type: "delta", delta, invocationId: "a".repeat(80), generation: 1, seq: Number.MAX_SAFE_INTEGER }) <= limit;
    const chunks = [...splitDelta(delta, fits)];
    assert.ok(chunks.length > 10); assert.ok(chunks.every(fits));
    assert.equal(chunks.map(item => item.content || "").join(""), content);
    assert.equal(chunks.map(item => item.reasoning_content || "").join(""), content);
    const calls = chunks.flatMap(item => item.tool_calls || []);
    assert.equal(calls.filter(call => call.id).length, 1);
    assert.equal(calls.filter(call => call.function.name).length, 1);
    assert.equal(calls.map(call => call.function.arguments).join(""), args);
    for (const chunk of chunks) assert.doesNotMatch(JSON.stringify(chunk), /\\u[dD][89abAB][0-9a-fA-F]{2}|\\u[dD][c-fC-F][0-9a-fA-F]{2}/, "no split surrogate pair");
  }
  assert.throws(() => [...splitDelta({ tool_calls: [{ index: 0, id: "x".repeat(1000), function: { name: "lookup", arguments: "a".repeat(1000) } }] },
    delta => Buffer.byteLength(JSON.stringify(delta)) < 300)], /metadata/);
  console.log("PASS CatPaw state: continuation claims, TTL/active anonymous, transactional capacity/global budget, scope leases, awaited event closure, Unicode/tool wire splitting");
}
main().catch(error => { console.error(error); process.exitCode = 1; });
